export function getTradeHubByLandmarkId(landmarkId?: string | null): TradeHubDef | null {
  if (!landmarkId) return null;
  return TRADE_HUBS.find((h) => h.landmarkId === landmarkId) ?? null;
}

export function getMerchantTierDef(tier: number): MerchantTierDef {
  const clamped = Math.max(1, Math.min(MERCHANT_TIERS.length, Math.round(tier || 1)));
  return MERCHANT_TIERS[clamped - 1];
}
